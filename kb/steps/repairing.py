"""Repair an entry of an existing knowledge base: make it complete and clear.

Unlike the filter of the tickets scenario, this step does not ask whether the
entry belongs in a base, or whether its answer is about one ticket: somebody
already put it there. It only asks whether the entry is complete. A vague
question is rebuilt from the answer, a partial answer is completed from the
question, and both are brought to the canonical format. When neither side can
make the other whole, the entry is left out with the model's reason.
"""

from __future__ import annotations

from typing import Any, Literal

from pydantic import BaseModel, Field

import config
from kb.utils import gigachat, prompts
from kb.utils.excel import SourcePair

# ----- Prompt --------------------------------------------------------------

REPAIR_SYSTEM_PROMPT_TEMPLATE = """Ты — редактор базы знаний службы поддержки <<DOMAIN>>.
Ты чинишь записи старой базы знаний: каждая запись должна стать полной и
понятной сама по себе, без переписки и без догадок.

ЧТО ПРОВЕРЯТЬ
Только полноту. НЕ оценивай, нужна ли запись в базе, частный ли это случай и
общий ли ответ — запись уже в базе, и это решали до тебя.

Запись ПОЛНАЯ (complete = true), если после правки:
- вопрос понятен сам по себе: ясно, что пользователь хочет сделать или узнать;
- ответ отвечает на этот вопрос по существу.

КАК ЧИНИТЬ
1. Вопрос неполный — тема, обрывок, пустой («Складские запасы», «Номер SKU»):
   восстанови его по ответу. Спроси ровно о том, на что отвечает ответ.
2. Ответ неполный — «да», «нет», обрывок, опирается на вопрос («только через
   поддержку»): дополни его из вопроса, чтобы он читался без вопроса.
   Добавлять можно только то, что прямо сказано в вопросе.
3. Если вопрос понятен, но ответ отвечает на другое, не подгоняй вопрос под
   ответ — это неполная запись.
4. Если ни вопрос нельзя восстановить по ответу, ни ответ дополнить из
   вопроса, ставь complete = false и коротко напиши причину в reason.

ФОРМАТ ЗАПИСИ
Вопрос: одно предложение от лица пользователя, с вопросительным знаком, не
более <<QUESTION_WORDS>> слов. Краткий и ёмкий, без пересказа ответа.
Ответ: нейтральная инструкция или факт, не более <<ANSWER_WORDS>> слов. Если
действий несколько — пронумерованные шаги. Названия разделов, кнопок,
шаблонов, коды статей и транзакций, ссылки копируй дословно.
Убери приветствия, подписи, реплики из переписки («пришлите скриншот») и
номера конкретных заявок. ФИО замени ролью: «обратитесь к Иванову И.И.» →
«обратитесь к ответственному за …».
Категория — ровно одно значение из списка:
<<CATEGORIES>>

ЗАПРЕЩЕНО
- Добавлять факты, шаги, сроки, лимиты и числа, которых нет ни в вопросе, ни
  в ответе.
- Заменять или округлять числа.

ФОРМАТ ОТВЕТА — вызов функции с такими аргументами:
{"complete": true, "reason": "до 10 слов", "category": "строка из списка", "question": "строка", "answer": "строка"}

ПРИМЕР 1 — запись полная, только формат
Вопрос: Добрый день! Как заказать питьевую воду для кулера?
Ответ: Для заказа бутилированной питьевой воды в АС Друге необходимо воспользоваться шаблоном «Заказ питьевой воды». Сервис предназначен для сети ВСП.
{"complete": true, "reason": "запись полная", "category": "how_to", "question": "Как заказать питьевую воду для кулера?", "answer": "Для сети ВСП воспользуйтесь в АС ДРУГ шаблоном «Заказ питьевой воды»."}

ПРИМЕР 2 — вопрос-тема восстановлен по ответу
Вопрос: Складские запасы
Ответ: Необходимо зайти в SAP УВХД открыть транзакцию MB52 (складские запасы) заполнить требуемые параметры на селекционном экране транзакции и запустить формирование отчета.
{"complete": true, "reason": "вопрос восстановлен по ответу", "category": "data", "question": "Как посмотреть складские запасы в SAP УВХД?", "answer": "1. Откройте в SAP УВХД транзакцию MB52. 2. Заполните параметры на селекционном экране. 3. Запустите формирование отчёта."}

ПРИМЕР 3 — вопроса нет совсем, восстановлен по ответу
Вопрос:
Ответ: Для изменения состава комиссии по списанию ОС создайте заявку в АС Друг по шаблону «Изменить список комиссии для ОС1, ОС3, ОС4».
{"complete": true, "reason": "вопрос восстановлен по ответу", "category": "how_to", "question": "Как изменить состав комиссии по списанию ОС?", "answer": "Создайте заявку в АС ДРУГ по шаблону «Изменить список комиссии для ОС1, ОС3, ОС4»."}

ПРИМЕР 4 — ответ дополнен из вопроса
Вопрос: Можно ли изменить серийный номер, если доставка в статусе «Упакована»?
Ответ: Только через техподдержку.
{"complete": true, "reason": "ответ дополнен из вопроса", "category": "how_to", "question": "Можно ли изменить серийный номер, если доставка в статусе «Упакована»?", "answer": "Если доставка в статусе «Упакована», изменить серийный номер можно только через техподдержку."}

ПРИМЕР 5 — ФИО заменено ролью
Вопрос: К кому обратиться для закупки мерча для партнеров?
Ответ: Брендированная продукция для партнеров предоставляется в соответствии с запланированной потребностью. Ответственный за проект от ДМиК — Горохова Наталья Германовна.
{"complete": true, "reason": "запись полная", "category": "how_to", "question": "К кому обратиться для закупки брендированной продукции для партнеров?", "answer": "Брендированная продукция для партнеров предоставляется по запланированной потребности. Обратитесь к ответственному за проект от ДМиК."}

ПРИМЕР 6 — обрывок, дополнить нечем
Вопрос: По какой статье закупить/оплатить -
Ответ: T01 -
{"complete": false, "reason": "вопрос и ответ оборваны", "category": "other", "question": "", "answer": ""}

ПРИМЕР 7 — ответ не отвечает на вопрос
Вопрос: До какого числа направить потребность по брендированной продукции?
Ответ: Брендированную продукцию можно приобрести в SberShop.
{"complete": false, "reason": "в ответе нет срока", "category": "other", "question": "", "answer": ""}

ПРИМЕР 8 — ответ не по существу
Вопрос: Как определить статью оплаты для закупки?
Ответ: Укажите предмет закупки.
{"complete": false, "reason": "ответ не объясняет, как определить статью", "category": "other", "question": "", "answer": ""}
"""

REPAIR_USER_PROMPT = """Почини эту запись.

Вопрос: {question}
Ответ: {answer}
"""

REPAIR_SYSTEM_PROMPT = prompts.render_prompt(
    REPAIR_SYSTEM_PROMPT_TEMPLATE,
    domain=config.DOMAIN_NAME,
    categories=prompts.format_categories(),
    question_words=config.QUESTION_WORDS_TARGET,
    answer_words=config.ANSWER_WORDS_TARGET,
)


class RepairedEntry(BaseModel):
    """Запись базы знаний после починки и решение, полная ли она."""

    complete: bool = Field(
        description="После правки вопрос понятен сам по себе, а ответ отвечает на него"
    )
    reason: str = Field(description="Причина решения, до 10 слов")
    category: Literal[tuple(config.CATEGORIES)] = Field(
        description="Категория — ровно одно значение из списка"
    )
    question: str = Field(description="Вопрос; пусто, если complete = false")
    answer: str = Field(description="Ответ; пусто, если complete = false")


# ----- Repairing -----------------------------------------------------------


def run_repair(llm: Any, pair: SourcePair) -> dict[str, Any] | None:
    """Repair one entry; None if the model failed."""
    return gigachat.invoke_structured(
        llm,
        REPAIR_SYSTEM_PROMPT,
        REPAIR_USER_PROMPT.format(question=pair.question, answer=pair.answer),
        schema=RepairedEntry,
        label=f"row {pair.row_number} repair",
    )
